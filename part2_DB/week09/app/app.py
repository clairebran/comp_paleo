import psycopg2
import psycopg2.extras
from psycopg2 import errors as pg_errors
from flask import Flask, render_template, request, redirect, url_for

from config import DSN

app = Flask(__name__)

# Controlled vocabulary for proxies.type (matches the CHECK in schema.sql).
# unit_of_analysis is generated by the database from type, so it is never entered here.
PROXY_TYPES = ['faunal_list', 'enamel_isotopes', 'paleosol_isotopes']


# ── Database helper ──────────────────────────────────────────────────────────

def get_db():
    return psycopg2.connect(DSN, cursor_factory=psycopg2.extras.RealDictCursor)


def blank_to_none(value):
    """Strip a form value; return None if it is empty (so the column gets NULL)."""
    value = (value or '').strip()
    return value or None


def locality_choices(cur):
    """Live SELECT feeding the locality dropdowns."""
    cur.execute("SELECT locality_id, site, formation, member FROM localities"
                " ORDER BY site, formation, member")
    return cur.fetchall()


def publication_choices(cur):
    """Live SELECT feeding the publication dropdowns."""
    cur.execute("SELECT publication_id, citation FROM publications ORDER BY citation")
    return cur.fetchall()


# ── Index ────────────────────────────────────────────────────────────────────

@app.route('/')
def index():
    conn = get_db()
    cur = conn.cursor()
    counts = {}
    # Fixed table names only (never user input), so building the query is safe.
    for table in ('localities', 'publications', 'hominin_occurrences', 'proxies'):
        cur.execute("SELECT COUNT(*) AS n FROM " + table)
        counts[table] = cur.fetchone()['n']
    conn.close()
    return render_template('index.html', counts=counts)


# ── Localities ───────────────────────────────────────────────────────────────

@app.route('/localities')
def list_localities():
    conn = get_db()
    cur = conn.cursor()
    cur.execute("SELECT * FROM localities ORDER BY country, site, formation, member")
    rows = cur.fetchall()
    conn.close()
    return render_template('localities_list.html', rows=rows)


@app.route('/localities/new', methods=['GET', 'POST'])
def new_locality():
    error = None
    if request.method == 'POST':
        conn = get_db()
        cur = conn.cursor()
        try:
            cur.execute(
                "INSERT INTO localities"
                " (country, site, formation, member, oldest_age_ma, youngest_age_ma)"
                " VALUES (%s, %s, %s, %s, %s, %s)",
                (blank_to_none(request.form.get('country')),
                 blank_to_none(request.form.get('site')),
                 blank_to_none(request.form.get('formation')),
                 blank_to_none(request.form.get('member')),
                 blank_to_none(request.form.get('oldest_age_ma')),
                 blank_to_none(request.form.get('youngest_age_ma')))
            )
            conn.commit()
            return redirect(url_for('list_localities'))
        except pg_errors.UniqueViolation:
            conn.rollback()
            error = "That site, formation, and member combination already exists."
        except pg_errors.NotNullViolation:
            conn.rollback()
            error = "Country, site, formation, and member are all required."
        except pg_errors.CheckViolation:
            conn.rollback()
            error = ("Ages cannot be negative, and the oldest age must be greater than "
                     "or equal to the youngest age (older = larger number in Ma).")
        except psycopg2.DataError:
            conn.rollback()
            error = "Ages must be numbers."
        finally:
            conn.close()
    return render_template('localities_form.html', error=error, form=request.form)


