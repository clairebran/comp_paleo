# ── Hominin occurrences ──────────────────────────────────────────────────────

@app.route('/occurrences')
def list_occurrences():
    conn = get_db()
    cur = conn.cursor()
    cur.execute("""
        SELECT h.occurrence_id, h.scientific_name,
               l.site, l.formation, l.member,
               p.citation
        FROM   hominin_occurrences h
        JOIN   localities   l ON l.locality_id    = h.locality_id
        JOIN   publications p ON p.publication_id = h.publication_id
        ORDER BY h.scientific_name, l.site, l.formation, l.member
    """)
    rows = cur.fetchall()
    conn.close()
    return render_template('occurrences_list.html', rows=rows)


@app.route('/occurrences/new', methods=['GET', 'POST'])
def new_occurrence():
    error = None
    conn = get_db()
    cur = conn.cursor()
    if request.method == 'POST':
        try:
            cur.execute(
                "INSERT INTO hominin_occurrences"
                " (scientific_name, locality_id, publication_id) VALUES (%s, %s, %s)",
                (blank_to_none(request.form.get('scientific_name')),
                 blank_to_none(request.form.get('locality_id')),
                 blank_to_none(request.form.get('publication_id')))
            )
            conn.commit()
            conn.close()
            return redirect(url_for('list_occurrences'))
        except pg_errors.NotNullViolation:
            conn.rollback()
            error = "Scientific name, locality, and publication are all required."
        except pg_errors.CheckViolation:
            conn.rollback()
            error = ("Scientific name must start with 'Paranthropus ' or 'Homo ' "
                     "(for example 'Homo habilis' or 'Paranthropus sp.').")
        except pg_errors.ForeignKeyViolation:
            conn.rollback()
            error = "The selected locality or publication no longer exists."
        finally:
            if not conn.closed:
                conn.close()

    # Re-open for the dropdown queries (the INSERT connection may be closed).
    conn = get_db()
    cur = conn.cursor()
    localities = locality_choices(cur)
    publications = publication_choices(cur)
    conn.close()
    return render_template('occurrences_form.html', error=error, form=request.form,
                           localities=localities, publications=publications)


# ── Proxies ──────────────────────────────────────────────────────────────────

@app.route('/proxies')
def list_proxies():
    conn = get_db()
    cur = conn.cursor()
    cur.execute("""
        SELECT x.proxy_id, x.type, x.unit_of_analysis,
               l.site, l.formation, l.member,
               p.citation
        FROM   proxies x
        JOIN   localities   l ON l.locality_id    = x.locality_id
        JOIN   publications p ON p.publication_id = x.publication_id
        ORDER BY l.site, l.formation, l.member, x.type
    """)
    rows = cur.fetchall()
    conn.close()
    return render_template('proxies_list.html', rows=rows)


@app.route('/proxies/new', methods=['GET', 'POST'])
def new_proxy():
    error = None
    if request.method == 'POST':
        conn = get_db()
        cur = conn.cursor()
        try:
            cur.execute(
                "INSERT INTO proxies (type, locality_id, publication_id)"
                " VALUES (%s, %s, %s)",
                (blank_to_none(request.form.get('type')),
                 blank_to_none(request.form.get('locality_id')),
                 blank_to_none(request.form.get('publication_id')))
            )
            conn.commit()
            conn.close()
            return redirect(url_for('list_proxies'))
        except pg_errors.UniqueViolation:
            conn.rollback()
            error = "That proxy type is already recorded for this locality and publication."
        except pg_errors.NotNullViolation:
            conn.rollback()
            error = ("Proxy type, locality, and publication are all required, and the type "
                     "must be faunal_list, enamel_isotopes, or paleosol_isotopes.")
        except pg_errors.CheckViolation:
            conn.rollback()
            error = "Proxy type must be faunal_list, enamel_isotopes, or paleosol_isotopes."
        except pg_errors.ForeignKeyViolation:
            conn.rollback()
            error = "The selected locality or publication no longer exists."
        finally:
            if not conn.closed:
                conn.close()

    conn = get_db()
    cur = conn.cursor()
    localities = locality_choices(cur)
    publications = publication_choices(cur)
    conn.close()
    return render_template('proxies_form.html', error=error, form=request.form,
                           localities=localities, publications=publications,
                           proxy_types=PROXY_TYPES)
